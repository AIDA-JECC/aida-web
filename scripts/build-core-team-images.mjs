const available = new Set(readdirSync(source));
for (const [file] of records) {
  if (!available.has(file)) throw new Error(`Missing source file: ${file}`);
}

const data = [];
for (const [file, id, name, designation, semester, rank] of records) {
  const input = join(source, file);
  for (const width of [400, 800]) {
    await sharp(input)
      .rotate()
      .resize(width, Math.round(width * 1.25), {
        fit: 'cover',
        position: sharp.strategy.attention,
      })
      .webp({ quality: 80, effort: 5 })
      .toFile(join(out, `${id}-${width}.webp`));
  }
  data.push({ id, name, designation, semester, rank, photo: `/core-team/${id}` });
  console.log(`ok ${name} — ${designation}`);
}

data.sort((a, b) => a.rank - b.rank || a.name.localeCompare(b.name));
